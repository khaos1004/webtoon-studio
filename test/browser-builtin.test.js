/** 내장 소재(public/materials): 목록·검색·컷에 붙이기·.wtoon 저장 후 다시 열기. http 로 서빙해서 실행(file:// 은 캔버스가 막힘) */
const path = require('path'), fs = require('fs'), http = require('http');
const { chromium } = require('playwright');
const ROOT = path.join(__dirname, 'out', 'web');
const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.webp': 'image/webp', '.png': 'image/png' };
let failed = 0;
const check = (n, ok, i = '') => { console.log(`${ok ? 'PASS' : 'FAIL'}  ${n}${i ? '  — ' + i : ''}`); if (!ok) failed++; };
(async () => {
  const srv = http.createServer((req, res) => {
    const f = path.join(ROOT, decodeURIComponent(req.url.split('?')[0]).replace(/\/$/, '/index.html'));
    if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
    res.writeHead(200, { 'content-type': MIME[path.extname(f)] || 'application/octet-stream' }); fs.createReadStream(f).pipe(res);
  }).listen(0);
  const base = `http://127.0.0.1:${srv.address().port}/`;
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ viewport: { width: 1500, height: 950 }, acceptDownloads: true });
  await ctx.addInitScript(() => { delete window.showSaveFilePicker; });
  const page = await ctx.newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
  await page.goto(base);
  await page.waitForSelector('.empty');
  await page.click('button:has-text("샘플 장면(콜라+흔들림)")');
  await page.waitForSelector('.cutCanvas');
  await page.click('.tabs button:has-text("소재")');
  await page.waitForSelector('.matHead:has-text("내장 소재")');
  const total = await page.locator('.matItem').count();
  const head = await page.locator('.matHead:has-text("내장 소재")').innerText();
  check('내장 소재 217개가 목록에 나온다', total === 217 && head.includes('217'), `${total} / ${head}`);
  check('섬네일은 작은 그림(t/…webp)을 쓴다', (await page.locator('.matItem img').first().getAttribute('src')).includes('/t/'));
  await page.waitForTimeout(800);
  const loaded = await page.evaluate(() => Array.from(document.querySelectorAll('.matItem img')).slice(0, 12).every((i) => i.complete && i.naturalWidth > 0));
  check('섬네일이 실제로 그려진다', loaded);
  await page.fill('[data-testid=mat-search]', '쭈웁');
  await page.waitForTimeout(200);
  const n1 = await page.locator('.matItem').count();
  check('이름 검색: “쭈웁”', n1 >= 1 && n1 < 20, `${n1}개`);
  await page.fill('[data-testid=mat-search]', '없는이름zzz');
  check('검색 결과 없음 안내', (await page.locator('.hint:has-text("맞는 소재가 없어요")').count()) === 1);
  await page.fill('[data-testid=mat-search]', '쭈웁');
  await page.locator('.matItem').first().click();
  check('내장 소재에는 삭제 버튼이 없다', (await page.locator('button:has-text("라이브러리에서 삭제")').count()) === 0);
  const snap = () => page.evaluate(() => { const c = document.querySelector('.cutCanvas'); return Array.from(c.getContext('2d').getImageData(0, 0, c.width, c.height).data); });
  const before = await snap();
  await page.click('button:has-text("컷에 한 장 붙이기")');
  await page.waitForTimeout(1500);
  const after = await snap();
  let diff = 0; for (let i = 0; i < before.length; i += 4) if (Math.abs(before[i] - after[i]) + Math.abs(before[i + 1] - after[i + 1]) + Math.abs(before[i + 2] - after[i + 2]) > 30) diff++;
  check('붙이면 컷 픽셀이 실제로 바뀐다', diff > 3000, `${diff}px`);
  await page.click('.tabs button:has-text("효과")');
  check('효과 레이어가 생긴다(이름에 효과음)', (await page.locator('.layerRow:has-text("효과음")').count()) >= 1);
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('button:has-text("저장(.wtoon)")')]);
  const wt = path.join(ROOT, '..', 'builtin.wtoon'); await dl.saveAs(wt);
  const j = JSON.parse(fs.readFileSync(wt, 'utf8'));
  const m = (j.materials || [])[0];
  check('.wtoon 에는 파일 주소가 아니라 그림(dataURL)이 들어간다', m && m.src.startsWith('data:image/') && !('builtin' in m) && !('thumb' in m) && m.id.startsWith('builtin-sfx-'), m ? m.src.slice(0, 22) : 'none');
  // 내장 소재가 없는 곳(다른 PC)에서 열어도 그림이 그대로 나오는지: 같은 파일을 manifest 없이 열기
  const p2 = await ctx.newPage();
  await p2.route('**/materials/manifest.json', (r) => r.fulfill({ status: 404, body: '' }));
  p2.on('pageerror', (e) => errors.push(e.message));
  await p2.goto(base); await p2.waitForSelector('.empty');
  if (await p2.locator('.recoverBar').count()) await p2.click('.recoverBar button:has-text("버리기")');
  await p2.setInputFiles('input[type=file][accept*=".wtoon"]', wt);
  await p2.waitForSelector('.cutCanvas'); await p2.waitForTimeout(1500);
  const px = await p2.evaluate(() => { const c = document.querySelector('.cutCanvas'); return Array.from(c.getContext('2d').getImageData(0, 0, c.width, c.height).data); });
  let d2 = 0; for (let i = 0; i < before.length; i += 4) if (Math.abs(before[i] - px[i]) + Math.abs(before[i + 1] - px[i + 1]) + Math.abs(before[i + 2] - px[i + 2]) > 30) d2++;
  check('내장 목록이 없는 환경에서 .wtoon 을 열어도 효과음이 그대로 보인다', d2 > 3000, `${d2}px`);
  await p2.click('.tabs button:has-text("소재")');
  check('그 환경에서는 내 소재로 표시(삭제 가능)', (await p2.locator('.matHead:has-text("내가 가져온")').count()) === 1);
  // 컷 밖 배경에 놓기
  await page.click('.tabs button:has-text("소재")');
  await page.fill('[data-testid=mat-search]', '허억'); await page.waitForTimeout(150);
  await page.locator('.matItem').first().click();
  await page.click('button:has-text("컷 밖 배경에 놓기")'); await page.waitForTimeout(1200);
  const [dl2] = await Promise.all([page.waitForEvent('download'), page.click('button:has-text("저장(.wtoon)")')]);
  const wt2 = path.join(ROOT, '..', 'builtin2.wtoon'); await dl2.saveAs(wt2);
  const j2 = JSON.parse(fs.readFileSync(wt2, 'utf8'));
  check('배경 이미지 레이어도 dataURL 로 저장된다', (j2.layers || []).some((l) => String(l.src).startsWith('data:image/')), JSON.stringify((j2.layers || []).map((l) => String(l.src).slice(0, 12))));
  check('콘솔/페이지 에러 없음', errors.filter((e) => !/404/.test(e)).length === 0, errors.slice(0, 2).join(' | '));
  await browser.close(); srv.close();
  console.log(failed ? `\n실패 ${failed}건` : '\n내장 소재 테스트 전부 통과'); process.exit(failed ? 1 : 0);
})().catch((e) => { console.error(e); process.exit(2); });
